base = Path('work/research/ui-localization-audit')
tasks = list(map(json.loads, (base / 'translation-task-A.jsonl').open()))
results = {}

def put(indices, title_jp, title_zh, body, notes=None, key_labels=None):
    for index in indices:
        t = tasks[index]
        source_body = [x['text'] for x in t['body_ocr']]
        source_body = [s.replace('ムボタン', '△ボタン').replace('ロボタン', '□ボタン').replace('uisEu', 'wiseup').replace('要索', '要素') for s in source_body]
        r = {'image_id': t['image_id'], 'title_zh': '教程 — ' + title_zh, 'body_zh': body,
             'source_text': title_jp + '\n' + '\n'.join(source_body),
             'source_title': title_jp, 'source_body': source_body,
             'source_png': t['png'], 'need_layout': False,
             'notes': '已逐图对照PNG；仅翻译顶部标题与底部说明，页码由原图保留。'}
        if notes:
            r['notes'] += ' ' + notes
        if key_labels:
            r['screenshot_key_labels'] = key_labels
        results[index] = r

