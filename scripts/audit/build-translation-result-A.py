# 排版风险只是文案标记，由绘制者以实际字体复核。
def fullwidth_width(s):
    return sum(1 if unicodedata.east_asian_width(c) in 'WF' else .5 for c in s)
for i, r in results.items():
    widths = [fullwidth_width(s) for s in r['body_zh']]
    r['body_fullwidth_units'] = widths
    if max(widths, default=0) > 30 or len(r['body_zh']) > 2:
        r['need_layout'] = True
        r['notes'] += ' 说明保留完整含义，需绘制阶段确认字号或文本框宽度。'

